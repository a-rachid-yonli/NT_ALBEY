export function translatePhrase(str, lang) {
  if (!str || typeof str !== 'string' || lang === 'fr') return str;
  const dict = PHRASE_TRANSLATIONS[lang];
  if (!dict) return str;

  // 1. Correspondance directe exacte
  if (dict[str]) return dict[str];
  if (PHRASE_TRANSLATIONS[str]?.[lang]) return PHRASE_TRANSLATIONS[str][lang];

  // 2. Correspondance sur la chaîne nettoyée (trim) en préservant les espaces autour
  const trimmed = str.trim();
  if (!trimmed) return str;
  if (dict[trimmed] || PHRASE_TRANSLATIONS[trimmed]?.[lang]) {
    const leading = str.match(/^\s*/)[0];
    const trailing = str.match(/\s*$/)[0];
    return leading + (dict[trimmed] || PHRASE_TRANSLATIONS[trimmed][lang]) + trailing;
  }

  // 3. Règles dynamiques (montants, compteurs, dates relatives)
  for (const rule of DYNAMIC_RULES) {
    const match = trimmed.match(rule.regex);
    if (match && typeof rule[lang] === 'function') {
      const leading = str.match(/^\s*/)[0];
      const trailing = str.match(/\s*$/)[0];
      return leading + rule[lang](match) + trailing;
    }
  }

  return str;
}
